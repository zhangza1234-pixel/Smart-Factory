def business_rows():
    parameters, faults = [], []
    for number, (line, device, station, model, specific, scenarios) in enumerate(DEVICES, 1):
        common = [('设备编号', f'DEMO-{line.upper()}-{number:03d}'), ('设备型号', model),
                  ('所属工序', station), ('运行模式', '仿真联调'), ('联网状态', '模拟在线')]
        parameters.extend((line, device, key, value + '（演示）', NOTICE) for key, value in common + specific)
        tenant = LINES[line][0]
        faults.extend((tenant, device, code, '【演示】' + description,
            NOTICE + ' 排查线索：' + solution + '。先记录异常与工件批次，是否停机和现场处置以经批准规程为准。', severity)
            for code, description, solution, severity in scenarios)
    return parameters, faults


def knowledge_documents():
    documents = []
    year = DEMO_YEAR
    for line, (tenant, plant, name) in LINES.items():
        devices = [device for device in DEVICES if device[0] == line]
        rules_family = f'演示资料 · {name}点检规则'
        for version_year in (year - 1, year):
            content = f'# {rules_family}\n\n{NOTICE}\n\n## 适用范围\n仅适用于{tenant}/{plant}/{line}的软件演示。不是正式标准。\n\n'
            content += '## 点检频次\n演示规则要求每班记录一次点检结果。\n\n## 异常闭环\n记录设备编号、时间、报警代码、产品批次及处理工单。'
            if version_year == year:
                content += '\n\n## 新版补充\n演示规则新增交接班异常复核，未闭环项需要记录责任人和下次复核时间。'
            else:
                content += '\n\n## 旧版范围\n本演示旧版未设置交接班异常复核字段。'
            documents.append(dict(line=line, tenant=tenant, plant=plant, family=rules_family, version=str(version_year),
                start=f'{version_year}-01-01', category='标准', access='操作员', content=content))
        operations = f'# 演示资料 · {name}设备与工序说明\n\n{NOTICE}\n'
        faults = f'# 演示资料 · {name}故障案例\n\n{NOTICE}\n'
        for _, device, station, model, specific, scenarios in devices:
            operations += f'\n## {device}\n设备型号：{model}（虚构）。所属工序：{station}。适用的演示点检规则系列为“{rules_family}”。\n'
            operations += '；'.join(f'{key}：{value}（演示）' for key, value in specific) + '。生产参数需查正式设备和工艺文件。\n'
            for code, description, solution, severity in scenarios:
                faults += f'\n## {device} {code}\n故障现象：{description}（演示）。严重程度标签：{severity}。排查线索：{solution}。\n'
                faults += '先核对设备编号、发生时间、产品批次及已批准规程；本案例不是实际设备报警码释义。\n'
        for family, content, category in [(f'演示资料 · {name}设备与工序说明', operations, '操作指南'),
                                          (f'演示资料 · {name}故障案例', faults, '故障手册')]:
            documents.append(dict(line=line, tenant=tenant, plant=plant, family=family, version=str(year),
                start=f'{year}-01-01', category=category, access='操作员', content=content))
    return documents
